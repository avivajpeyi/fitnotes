#!/usr/bin/env python3
"""Compute next-session target weights/reps via double progression and write
data/active_targets.json (the single source of truth the web app reads).

Usage:
    python3 scripts/compute_targets.py [--csv data/fitnotes_export.csv] [--unit kg|lb]
                                        [--routines data/routines.json]
                                        [--out data/active_targets.json]
                                        [--print <routine-id>]

Progression rules (see CLAUDE.md for the full philosophy):
  - 2-rep-range Double Progression: if every logged set for an exercise's last
    session met or exceeded the top of its target rep range, increase the load
    by that exercise's `progressionIncrementKg` (default 2.5kg) next session and
    reset the rep target back to the bottom of the range.
  - Otherwise, stay at the same weight and aim to add one more rep on the
    hardest set next time.
  - Plateau flag: if the working weight has been unchanged for 3+ consecutive
    logged sessions AND the max reps achieved hasn't increased across them,
    the exercise is flagged `"status": "plateau"` with a suggestion to deload
    or swap variations.
"""
from __future__ import annotations

import argparse
import json
import shutil
from datetime import date
from pathlib import Path

import parse_fitnotes as pf

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_ROUTINES = REPO_ROOT / "data" / "routines.json"
DEFAULT_OUT = REPO_ROOT / "data" / "active_targets.json"
WEB_DATA_DIR = REPO_ROOT / "web" / "public" / "data"

PLATEAU_SESSION_THRESHOLD = 3


def load_routines(path: Path) -> dict:
    return json.loads(path.read_text())


def compute_exercise_target(cfg: dict, sessions: list[dict]) -> dict:
    rep_min, rep_max = cfg["repRangeMin"], cfg["repRangeMax"]
    increment = cfg.get("progressionIncrementKg", 2.5)

    if not sessions:
        return {
            "name": cfg["name"],
            "targetWeightKg": cfg.get("startWeightKg", 20),
            "repRangeMin": rep_min,
            "repRangeMax": rep_max,
            "targetSets": cfg["sets"],
            "status": "new",
            "plateauWeeks": 0,
            "lastSession": None,
            "e1rmTrend": [],
            "note": "No logged history yet. Using starting weight from routines.json.",
        }

    last = sessions[-1]
    last_weight = last["max_weight_kg"]
    all_top_of_range = all(s["reps"] >= rep_max for s in last["sets"])

    # --- plateau detection: consecutive most-recent sessions at the same
    # working weight with no improvement in max reps achieved ---
    streak = 1
    for sess in reversed(sessions[:-1]):
        if sess["max_weight_kg"] == last_weight and sess["max_reps"] <= last["max_reps"]:
            streak += 1
        else:
            break
    is_plateau = streak >= PLATEAU_SESSION_THRESHOLD and not all_top_of_range

    if all_top_of_range:
        target_weight = round(last_weight + increment, 2)
        note = (
            f"Hit top of rep range ({rep_max}) on every set last session "
            f"({last['date']}) — load increased by {increment}kg."
        )
        status = "progressing"
    elif is_plateau:
        target_weight = last_weight
        note = (
            f"Stuck at {last_weight}kg for {streak} sessions without a rep increase. "
            "Consider a deload (-10%) or swapping the variation next block."
        )
        status = "plateau"
    else:
        target_weight = last_weight
        note = f"Stay at {last_weight}kg — aim to add a rep on your hardest set (last: {last['max_reps']})."
        status = "hold"

    e1rm_trend = [
        {"date": s["date"], "e1rm": s["top_set_e1rm"]} for s in sessions[-6:]
    ]

    return {
        "name": cfg["name"],
        "targetWeightKg": target_weight,
        "repRangeMin": rep_min,
        "repRangeMax": rep_max,
        "targetSets": cfg["sets"],
        "status": status,
        "plateauWeeks": streak if is_plateau else 0,
        "lastSession": {
            "date": last["date"],
            "sets": last["sets"],
            "topSetE1rm": last["top_set_e1rm"],
        },
        "e1rmTrend": e1rm_trend,
        "note": note,
    }


def compute_active_targets(routines_cfg: dict, sessions_by_exercise: dict[str, list[dict]]) -> dict:
    routines_out = []
    for routine in routines_cfg["routines"]:
        exercises_out = [
            compute_exercise_target(ex_cfg, sessions_by_exercise.get(ex_cfg["name"], []))
            for ex_cfg in routine["exercises"]
        ]
        routines_out.append(
            {"id": routine["id"], "name": routine["name"], "exercises": exercises_out}
        )
    return {
        "_comment": (
            "Generated by scripts/compute_targets.py. Do not hand-edit fields other "
            "than initial placeholders. This file is the single source of truth read "
            "by the web app (a copy is synced to web/public/data/active_targets.json)."
        ),
        "schemaVersion": 1,
        "generatedAt": date.today().isoformat(),
        "routines": routines_out,
    }


def status_symbol(status: str) -> str:
    return {"progressing": "↑", "hold": "→", "plateau": "⚠", "new": "•"}.get(status, "-")


def print_routine_summary(active_targets: dict, routine_id: str) -> None:
    routine = next((r for r in active_targets["routines"] if r["id"] == routine_id or r["name"].lower() == routine_id.lower()), None)
    if routine is None:
        print(f"No routine matching '{routine_id}'. Available: "
              f"{', '.join(r['id'] for r in active_targets['routines'])}")
        return

    title = f"{routine['name'].upper()} — Targets for {active_targets['generatedAt']}"
    print(title)
    print("=" * 78)
    print(f"{'Exercise':<32} {'Target':>9} {'Reps':>8} {'Sets':>5}  Status")
    print("-" * 78)
    for ex in routine["exercises"]:
        target = f"{ex['targetWeightKg']}kg"
        reps = f"{ex['repRangeMin']}-{ex['repRangeMax']}"
        sym = status_symbol(ex["status"])
        print(f"{ex['name']:<32} {target:>9} {reps:>8} {ex['targetSets']:>5}  {sym} {ex['note']}")
    print("=" * 78)


def sync_to_web(active_targets: dict, routines_cfg: dict) -> None:
    if not WEB_DATA_DIR.parent.exists():
        return
    WEB_DATA_DIR.mkdir(parents=True, exist_ok=True)
    (WEB_DATA_DIR / "active_targets.json").write_text(json.dumps(active_targets, indent=2) + "\n")
    (WEB_DATA_DIR / "routines.json").write_text(json.dumps(routines_cfg, indent=2) + "\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csv", type=Path, default=pf.DEFAULT_CSV)
    parser.add_argument("--unit", choices=["kg", "lb"], default="kg")
    parser.add_argument("--routines", type=Path, default=DEFAULT_ROUTINES)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--print", dest="print_routine", metavar="ROUTINE_ID",
                         help="Print a terminal target sheet for this routine id after computing")
    args = parser.parse_args(argv)

    sets = pf.parse_csv(args.csv, unit=args.unit)
    sessions_by_exercise = pf.group_sessions(sets)
    routines_cfg = load_routines(args.routines)

    active_targets = compute_active_targets(routines_cfg, sessions_by_exercise)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(active_targets, indent=2) + "\n")
    sync_to_web(active_targets, routines_cfg)

    print(f"Wrote {args.out}")
    if (WEB_DATA_DIR / "active_targets.json").exists():
        print(f"Synced copy to {WEB_DATA_DIR}")

    if args.print_routine:
        print()
        print_routine_summary(active_targets, args.print_routine)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
